//! markdown-to-rust: Regenerate `registry_mirrors/mod.rs` from the directory.
//!
//! Writes `crates/data_core/src/registry_mirrors/mod.rs` with one `pub mod`
//! line per `.rs` file in that directory. The binary reads, converts and
//! removes no markdown file; the mirror files themselves come from
//! `registry-emit`.

use anyhow::{Context, Result};
use clap::Parser;
use std::{fs, path::Path};

const MIRRORS_DIR: &str = "crates/data_core/src/registry_mirrors";

#[derive(Parser, Debug)]
#[command(
    name = "markdown-to-rust",
    about = "Regenerate registry_mirrors/mod.rs from the directory listing"
)]
struct Cli {}

/// Rewrites `mod.rs` from the `.rs` files in the mirrors directory. This
/// function writes `mod.rs` only.
fn write_mod_listing(root: &Path) -> Result<()> {
    let mirrors_dir = root.join(MIRRORS_DIR);
    if mirrors_dir.exists() {
        let mut mods = Vec::new();
        for entry in fs::read_dir(&mirrors_dir)? {
            let entry = entry?;
            let path = entry.path();
            if path.is_file() && path.extension().and_then(|s| s.to_str()) == Some("rs") {
                let stem = path
                    .file_stem()
                    .and_then(|s| s.to_str())
                    .context("mirror file name is not UTF-8")?;
                if stem != "mod" {
                    mods.push(format!("pub mod {};", stem));
                }
            }
        }
        mods.sort();
        // PH-4.B audit-lane lens: every file under registry_mirrors/ is
        // auto-generated from registry/*.toml. Clippy / rust-analyzer
        // warnings there are noise -- they cannot be fixed in source
        // because the source IS the registry TOML, and any "fix" is
        // overwritten on the next emit. Suppress at the module level.
        let header = "// @generated by registry-emit; do not edit. Source: registry/canonical/control_plane.sqlite3\n\
                      //\n\
                      // PH-4.B audit-lane lens: silence all clippy warnings inside this module\n\
                      // tree. Every file under registry_mirrors/ is auto-generated by the\n\
                      // `cargo run -p xtask -- registry-emit-all-mirrors` lane and is rewritten\n\
                      // on every export. Edits made here are LOST on the next regen.\n\
                      #![allow(warnings)]\n\
                      #![allow(clippy::all)]\n\
                      #![allow(clippy::pedantic)]\n\
                      #![allow(clippy::nursery)]\n\
                      \n";
        let mod_content = format!("{}{}\n", header, mods.join("\n"));
        fs::write(mirrors_dir.join("mod.rs"), mod_content).context("write mirrors/mod.rs")?;
    }
    Ok(())
}

fn main() -> Result<()> {
    Cli::parse();
    let root = repo_root::resolve!();
    write_mod_listing(&root)?;
    println!("Wrote {MIRRORS_DIR}/mod.rs.");
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn listing_rewrites_mod_rs_and_leaves_other_files_untouched() {
        let tmp = tempfile::tempdir().unwrap();
        let dir = tmp.path().join(MIRRORS_DIR);
        fs::create_dir_all(&dir).unwrap();
        fs::write(dir.join("mod.rs"), "stale\n").unwrap();
        fs::write(dir.join("b_mirror.rs"), "//! b\n").unwrap();
        fs::write(dir.join("a_mirror.rs"), "//! a\n").unwrap();
        let readme = tmp.path().join("README.md");
        fs::write(&readme, "# keep\n").unwrap();

        write_mod_listing(tmp.path()).unwrap();

        let mod_rs = fs::read_to_string(dir.join("mod.rs")).unwrap();
        assert!(mod_rs.ends_with("pub mod a_mirror;\npub mod b_mirror;\n"));
        assert!(!mod_rs.contains("pub mod mod;"));
        assert_eq!(
            fs::read_to_string(dir.join("a_mirror.rs")).unwrap(),
            "//! a\n"
        );
        assert_eq!(fs::read_to_string(readme).unwrap(), "# keep\n");
    }

    #[test]
    fn cli_accepts_no_arguments_and_rejects_conversion_flags() {
        assert!(Cli::try_parse_from(["markdown-to-rust"]).is_ok());
        assert!(Cli::try_parse_from(["markdown-to-rust", "--mod-only"]).is_err());
    }
}
