(** Cayley-Dickson Schreier signs on recursively doubled Boolean cubes.

    The sign recurrence matches the four standard Cayley-Dickson branches.
    The span is generated by those signs; the proposed code description is
    a separate predicate. The last pair component is the highest index bit.
    Commutator cancellation proves the upper containment; finite delta
    expansions and two independent units supply explicit lower witnesses. *)

From Stdlib Require Import Bool Arith Lia List btauto.Btauto.
Import ListNotations.

Fixpoint cube (order : nat) : Type :=
  match order with O => unit | S lower => (cube lower * bool)%type end.

Fixpoint cube_zero (order : nat) : cube order :=
  match order with O => tt | S lower => (cube_zero lower, false) end.

Fixpoint cube_xor (order : nat) : cube order -> cube order -> cube order :=
  match order with
  | O => fun _ _ => tt
  | S lower => fun left right =>
      (cube_xor lower (fst left) (fst right), xorb (snd left) (snd right))
  end.

Fixpoint cube_equal (order : nat) : cube order -> cube order -> bool :=
  match order with
  | O => fun _ _ => true
  | S lower => fun left right =>
      andb (cube_equal lower (fst left) (fst right)) (Bool.eqb (snd left) (snd right))
  end.

Definition cube_nonzero (order : nat) (value : cube order) : bool :=
  negb (cube_equal order value (cube_zero order)).

Fixpoint sign_exponent (order : nat) : cube order -> cube order -> bool :=
  match order with
  | O => fun _ _ => false
  | S lower => fun left right =>
      xorb (if snd right then sign_exponent lower (fst right) (fst left)
            else sign_exponent lower (fst left) (fst right))
        (andb (snd left) (xorb (cube_nonzero lower (fst right)) (snd right)))
  end.

Definition schreier (order : nat) (left right input : cube order) : bool :=
  xorb (xorb (sign_exponent order right input)
             (sign_exponent order left (cube_xor order right input)))
       (sign_exponent order (cube_xor order left right) input).

Fixpoint cube_sum (order : nat) : (cube order -> bool) -> bool :=
  match order with
  | O => fun function => function tt
  | S lower => fun function => xorb
      (cube_sum lower (fun input => function (input, false)))
      (cube_sum lower (fun input => function (input, true)))
  end.

Lemma cube_equal_reflexive : forall order (value : cube order),
    cube_equal order value value = true.
Proof.
  induction order; intros value; [reflexivity |].
  destruct value as [lower high]. simpl. rewrite IHorder. destruct high; reflexivity.
Qed.

Lemma cube_equal_symmetric : forall order (left right : cube order),
    cube_equal order left right = cube_equal order right left.
Proof.
  induction order; intros left right; [reflexivity |].
  destruct left as [left low], right as [right high]. simpl.
  rewrite IHorder. destruct low, high; reflexivity.
Qed.

Lemma cube_equal_spec : forall order (left right : cube order),
    cube_equal order left right = true <-> left = right.
Proof.
  induction order; intros left right.
  - destruct left, right. split; reflexivity.
  - destruct left as [left low], right as [right high]. simpl. split.
    + intros equal. apply andb_true_iff in equal as [cube_part bit_part].
      apply IHorder in cube_part. subst.
      destruct low, high; simpl in bit_part; try discriminate; reflexivity.
    + intros equal. injection equal as cube_part bit_part. subst.
      apply andb_true_iff. split; [apply IHorder; reflexivity | destruct high; reflexivity].
Qed.

Lemma cube_nonzero_double : forall order (value : cube order) high,
    cube_nonzero (S order) (value, high) = orb (cube_nonzero order value) high.
Proof.
  intros order value high. unfold cube_nonzero. simpl.
  destruct high, (cube_equal order value (cube_zero order)); reflexivity.
Qed.

Lemma cube_nonzero_zero : forall order, cube_nonzero order (cube_zero order) = false.
Proof. intros order. unfold cube_nonzero. rewrite cube_equal_reflexive. reflexivity. Qed.

Lemma cube_xor_zero : forall order (value : cube order),
    cube_xor order value (cube_zero order) = value.
Proof.
  induction order; intros value; [destruct value; reflexivity |].
  destruct value as [lower high]. simpl. rewrite IHorder, xorb_false_r. reflexivity.
Qed.

Lemma cube_xor_commutative : forall order (left right : cube order),
    cube_xor order left right = cube_xor order right left.
Proof.
  induction order; intros left right; [reflexivity |].
  destruct left as [left low], right as [right high]. simpl.
  rewrite IHorder, xorb_comm. reflexivity.
Qed.

Lemma cube_equal_translate : forall order (left right input : cube order),
    cube_equal order (cube_xor order left input) right =
    cube_equal order input (cube_xor order left right).
Proof.
  induction order; intros left right input; [reflexivity |].
  destruct left as [left left_high], right as [right right_high], input as [input high].
  simpl. rewrite IHorder. destruct left_high, right_high, high; reflexivity.
Qed.

Lemma sign_zero_left : forall order input,
    sign_exponent order (cube_zero order) input = false /\
    sign_exponent order input (cube_zero order) = false.
Proof.
  induction order; intros input; [split; reflexivity |].
  destruct input as [input high]. simpl.
  destruct (IHorder input) as [zero_left zero_right].
  rewrite cube_nonzero_zero, zero_right, zero_left.
  destruct high; split; reflexivity.
Qed.

Lemma sign_commutator : forall order (left right : cube order),
    xorb (sign_exponent order left right) (sign_exponent order right left) =
    xorb (cube_nonzero order left)
      (xorb (negb (cube_nonzero order right)) (cube_equal order left right)).
Proof.
  induction order; intros left right; [reflexivity |].
  destruct left as [left left_high], right as [right right_high].
  rewrite !cube_nonzero_double. cbn [sign_exponent cube_equal fst snd].
  pose proof (IHorder left right) as lower_commutator.
  destruct left_high, right_high; simpl;
    destruct (sign_exponent order left right), (sign_exponent order right left),
      (cube_nonzero order left), (cube_nonzero order right),
      (cube_equal order left right); simpl in *; congruence.
Qed.

Lemma cube_sum_extensional : forall order (left right : cube order -> bool),
    (forall input, left input = right input) -> cube_sum order left = cube_sum order right.
Proof.
  induction order; intros left right equal; simpl; [apply equal |].
  rewrite (IHorder (fun input => left (input, false)) (fun input => right (input, false))),
    (IHorder (fun input => left (input, true)) (fun input => right (input, true))); auto.
Qed.

Lemma cube_sum_xor : forall order (left right : cube order -> bool),
    cube_sum order (fun input => xorb (left input) (right input)) =
    xorb (cube_sum order left) (cube_sum order right).
Proof.
  induction order; intros left right; simpl; [reflexivity |].
  rewrite !IHorder. btauto.
Qed.

Lemma cube_sum_false : forall order, cube_sum order (fun _ => false) = false.
Proof. induction order; simpl; [reflexivity | rewrite IHorder; reflexivity]. Qed.

Lemma cube_sum_constant : forall order value,
    cube_sum (S order) (fun _ => value) = false.
Proof. intros order value. simpl. apply xorb_nilpotent. Qed.

Lemma cube_sum_and_constant : forall order (function : cube order -> bool) constant,
    cube_sum order (fun input => andb constant (function input)) =
    andb constant (cube_sum order function).
Proof.
  intros order function [].
  - simpl. reflexivity.
  - simpl. apply cube_sum_false.
Qed.

Lemma cube_sum_delta : forall order (target : cube order),
    cube_sum order (fun input => cube_equal order input target) = true.
Proof.
  induction order; intros target; [reflexivity |].
  destruct target as [target high]. cbn [cube_sum cube_equal fst snd].
  assert (sum_right : forall value,
    cube_sum order (fun input => andb (cube_equal order input target) value) = value).
  { intros value. transitivity
      (cube_sum order (fun input => andb value (cube_equal order input target))).
    - apply cube_sum_extensional. intros input. apply andb_comm.
    - rewrite cube_sum_and_constant, IHorder. apply andb_true_r. }
  rewrite !sum_right. destruct high; reflexivity.
Qed.

Lemma cube_sum_translation : forall order (shift : cube order) function,
    cube_sum order (fun input => function (cube_xor order shift input)) =
    cube_sum order function.
Proof.
  induction order; intros shift function.
  - destruct shift. reflexivity.
  - destruct shift as [shift high]. cbn [cube_sum cube_xor fst snd].
    rewrite (IHorder shift (fun input => function (input, xorb high false))),
      (IHorder shift (fun input => function (input, xorb high true))).
    destruct high; simpl; [apply xorb_comm | reflexivity].
Qed.

Lemma sign_row_column_parity_equal : forall order (value : cube (S order)),
    cube_sum (S order) (fun input => sign_exponent (S order) value input) =
    cube_sum (S order) (fun input => sign_exponent (S order) input value).
Proof.
  intros order value.
  assert (parity : xorb
    (cube_sum (S order) (fun input => sign_exponent (S order) value input))
    (cube_sum (S order) (fun input => sign_exponent (S order) input value)) = false).
  { rewrite <- cube_sum_xor.
    transitivity (cube_sum (S order) (fun input =>
      xorb (cube_nonzero (S order) value)
        (xorb (cube_equal (S order) input (cube_zero (S order)))
              (cube_equal (S order) input value)))).
    - apply cube_sum_extensional. intros input. rewrite sign_commutator.
      unfold cube_nonzero. rewrite negb_involutive,
        (cube_equal_symmetric (S order) value input). reflexivity.
    - rewrite !cube_sum_xor, cube_sum_constant, !cube_sum_delta. reflexivity. }
  exact (xorb_eq _ _ parity).
Qed.

Lemma sign_row_even : forall order (value : cube (S (S order))),
    cube_sum (S (S order)) (fun input => sign_exponent (S (S order)) value input) = false.
Proof.
  intros order [value high].
  change (xorb
    (cube_sum (S order) (fun input => xorb (sign_exponent (S order) value input)
      (andb high (xorb (cube_nonzero (S order) input) false))))
    (cube_sum (S order) (fun input => xorb (sign_exponent (S order) input value)
      (andb high (xorb (cube_nonzero (S order) input) true)))) = false).
  rewrite !cube_sum_xor, !cube_sum_and_constant, !cube_sum_xor,
    !cube_sum_constant, sign_row_column_parity_equal. btauto.
Qed.

Lemma sign_column_even : forall order (value : cube (S (S order))),
    cube_sum (S (S order)) (fun input => sign_exponent (S (S order)) input value) = false.
Proof.
  intros order value. rewrite <- sign_row_column_parity_equal. apply sign_row_even.
Qed.

Lemma sign_transpose : forall order (left right : cube order),
    sign_exponent order right left =
    xorb (sign_exponent order left right)
      (xorb (cube_nonzero order left)
        (xorb (negb (cube_nonzero order right)) (cube_equal order left right))).
Proof.
  intros order left right. pose proof (sign_commutator order left right) as commute.
  rewrite <- commute. btauto.
Qed.

Lemma schreier_high_difference : forall order (left right input : cube order) left_high right_high,
    xorb (schreier (S order) (left, left_high) (right, right_high) (input, false))
         (schreier (S order) (left, left_high) (right, right_high) (input, true)) =
    xorb (cube_nonzero order left)
      (xorb (cube_nonzero order right) (cube_nonzero order (cube_xor order left right))).
Proof.
  intros order left right input left_high right_high.
  unfold schreier. cbn [sign_exponent cube_xor fst snd].
  rewrite (sign_transpose order right input),
    (sign_transpose order (cube_xor order left right) input).
  destruct right_high; simpl;
    rewrite (sign_transpose order left (cube_xor order right input));
    unfold cube_nonzero;
    rewrite (cube_equal_translate order right (cube_zero order) input), cube_xor_zero,
      (cube_equal_symmetric order left (cube_xor order right input)),
      (cube_equal_translate order right left input),
      (cube_xor_commutative order right left),
      (cube_equal_symmetric order right input),
      (cube_equal_symmetric order (cube_xor order left right) input);
    btauto.
Qed.

Lemma schreier_closed_form : forall order (left right input : cube order)
    left_high right_high input_high,
    schreier (S order) (left, left_high) (right, right_high) (input, input_high) =
    xorb
      (xorb (if input_high then sign_exponent order input right else sign_exponent order right input)
        (if input_high then sign_exponent order input (cube_xor order left right)
         else sign_exponent order (cube_xor order left right) input))
      (xorb (if xorb right_high input_high
        then sign_exponent order (cube_xor order right input) left
        else sign_exponent order left (cube_xor order right input))
        (andb left_high (xorb
          (xorb (cube_equal order input (cube_zero order)) (cube_equal order input right)) right_high))).
Proof.
  intros order left right input left_high right_high input_high.
  unfold schreier. cbn [sign_exponent cube_xor fst snd].
  unfold cube_nonzero. rewrite cube_equal_translate, cube_xor_zero.
  destruct input_high, right_high; simpl; btauto.
Qed.

Lemma schreier_low_even : forall order
    (left right : cube (S (S order))) left_high right_high,
    cube_sum (S (S order)) (fun input =>
      schreier (S (S (S order))) (left, left_high) (right, right_high) (input, false)) = false.
Proof.
  intros order left right left_high right_high.
  transitivity (cube_sum (S (S order)) (fun input =>
    xorb (xorb (sign_exponent (S (S order)) right input)
      (sign_exponent (S (S order)) (cube_xor (S (S order)) left right) input))
      (xorb (if right_high then sign_exponent (S (S order)) (cube_xor (S (S order)) right input) left
        else sign_exponent (S (S order)) left (cube_xor (S (S order)) right input))
        (andb left_high (xorb
          (xorb (cube_equal (S (S order)) input (cube_zero (S (S order))))
            (cube_equal (S (S order)) input right)) right_high))))).
  - apply cube_sum_extensional. intros input. rewrite schreier_closed_form.
    destruct right_high; reflexivity.
  - rewrite !cube_sum_xor, !cube_sum_and_constant, !cube_sum_xor,
      cube_sum_constant, !cube_sum_delta, !sign_row_even.
    destruct right_high.
    + rewrite (cube_sum_translation (S (S order)) right
        (fun input => sign_exponent (S (S order)) input left)), sign_column_even.
      destruct left_high; reflexivity.
    + rewrite (cube_sum_translation (S (S order)) right
        (fun input => sign_exponent (S (S order)) left input)), sign_row_even.
      destruct left_high; reflexivity.
Qed.

(** The span definition depends only on the actual Schreier generators. *)
Inductive sign_span (order : nat) : (cube order -> bool) -> Prop :=
| span_zero : sign_span order (fun _ => false)
| span_generator : forall left right, sign_span order (schreier order left right)
| span_add : forall left right, sign_span order left -> sign_span order right ->
    sign_span order (fun input => xorb (left input) (right input))
| span_extensional : forall left right, sign_span order left ->
    (forall input, left input = right input) -> sign_span order right.

Definition even_lower_code (order : nat) (function : cube (S order) -> bool) : Prop :=
  exists lower_function high_coefficient,
    cube_sum order lower_function = false /\
    forall lower high, function (lower, high) =
      xorb (lower_function lower) (andb high_coefficient high).

Theorem schreier_span_upper : forall order function,
    sign_span (S (S (S order))) function -> even_lower_code (S (S order)) function.
Proof.
  intros order function member. induction member.
  - exists (fun _ => false), false. split; [apply cube_sum_false | reflexivity].
  - destruct left as [left left_high], right as [right right_high].
    exists (fun input => schreier (S (S (S order))) (left, left_high) (right, right_high) (input, false)).
    exists (xorb (cube_nonzero (S (S order)) left)
      (xorb (cube_nonzero (S (S order)) right)
        (cube_nonzero (S (S order)) (cube_xor (S (S order)) left right)))).
    split; [apply schreier_low_even |]. intros lower [].
    + pose proof (schreier_high_difference (S (S order)) left right lower left_high right_high) as difference.
      rewrite andb_true_r, <- difference. cbv beta.
      rewrite <- xorb_assoc_reverse, xorb_nilpotent. reflexivity.
    + rewrite andb_false_r, xorb_false_r. reflexivity.
  - destruct IHmember1 as [left_lower [left_high [left_even left_value]]].
    destruct IHmember2 as [right_lower [right_high [right_even right_value]]].
    exists (fun input => xorb (left_lower input) (right_lower input)), (xorb left_high right_high).
    split; [rewrite cube_sum_xor, left_even, right_even; reflexivity |].
    intros lower high. rewrite left_value, right_value. btauto.
  - destruct IHmember as [lower_function [high_coefficient [parity value]]].
    exists lower_function, high_coefficient. split; [exact parity |].
    intros lower high. rewrite <- H. apply value.
Qed.

Lemma span_cube_sum : forall parameter_order order
    (family : cube parameter_order -> cube order -> bool),
    (forall parameter, sign_span order (family parameter)) ->
    sign_span order (fun input => cube_sum parameter_order (fun parameter => family parameter input)).
Proof.
  induction parameter_order; intros order family members.
  - apply members.
  - simpl. apply span_add; apply IHparameter_order; intros parameter; apply members.
Qed.

Lemma cube_sum_sampling : forall order (function : cube order -> bool) target,
    cube_sum order (fun input => andb (function input) (cube_equal order input target)) = function target.
Proof.
  induction order; intros function target.
  - destruct target. simpl. apply andb_true_r.
  - destruct target as [target target_high]. cbn [cube_sum cube_equal fst snd].
    assert (slice : forall high,
      cube_sum order (fun input => andb (function (input, high))
        (andb (cube_equal order input target) (Bool.eqb high target_high))) =
      andb (Bool.eqb high target_high) (function (target, high))).
    { intros high. transitivity (cube_sum order (fun input =>
        andb (Bool.eqb high target_high) (andb (function (input, high)) (cube_equal order input target)))).
      - apply cube_sum_extensional. intros input. btauto.
      - rewrite cube_sum_and_constant, IHorder. reflexivity. }
    rewrite !slice. destruct target_high; simpl; btauto.
Qed.

Lemma schreier_delta_pair : forall order (target input : cube order) high,
    schreier (S order) (cube_zero order, true) (target, false) (input, high) =
    xorb (cube_equal order input (cube_zero order)) (cube_equal order input target).
Proof.
  intros order target input high. rewrite schreier_closed_form.
  rewrite cube_xor_commutative, cube_xor_zero.
  destruct high; simpl;
    rewrite ?(proj1 (sign_zero_left order (cube_xor order target input))),
      ?(proj2 (sign_zero_left order (cube_xor order target input))); btauto.
Qed.

Lemma even_function_delta_expansion : forall order (function : cube order -> bool),
    cube_sum order function = false -> forall input,
    cube_sum order (fun target => andb (function target)
      (xorb (cube_equal order input (cube_zero order)) (cube_equal order input target))) = function input.
Proof.
  intros order function parity input.
  transitivity (cube_sum order (fun target =>
    xorb (andb (cube_equal order input (cube_zero order)) (function target))
      (andb (function target) (cube_equal order target input)))).
  - apply cube_sum_extensional. intros target.
    rewrite (cube_equal_symmetric order input target). btauto.
  - rewrite cube_sum_xor, cube_sum_and_constant, cube_sum_sampling, parity.
    rewrite andb_false_r. reflexivity.
Qed.

Lemma even_lower_in_span : forall order (function : cube order -> bool),
    cube_sum order function = false ->
    sign_span (S order) (fun input => function (fst input)).
Proof.
  intros order function parity.
  eapply span_extensional with (left := fun input => cube_sum order (fun target =>
    andb (function target) (schreier (S order) (cube_zero order, true) (target, false) input))).
  - apply span_cube_sum. intros target. destruct (function target); simpl.
    + apply span_generator.
    + apply span_zero.
  - intros [input high]. transitivity (cube_sum order (fun target => andb (function target)
      (xorb (cube_equal order input (cube_zero order)) (cube_equal order input target)))).
    + apply cube_sum_extensional. intros target. rewrite schreier_delta_pair. reflexivity.
    + apply even_function_delta_expansion. exact parity.
Qed.

Definition independent_first (order : nat) : cube (S (S order)) :=
  ((cube_zero order, true), false).
Definition independent_second (order : nat) : cube (S (S order)) :=
  ((cube_zero order, false), true).

Lemma independent_high_coefficient : forall order,
    xorb (cube_nonzero (S (S order)) (independent_first order))
      (xorb (cube_nonzero (S (S order)) (independent_second order))
        (cube_nonzero (S (S order))
          (cube_xor (S (S order)) (independent_first order) (independent_second order)))) = true.
Proof.
  intros order. unfold independent_first, independent_second.
  cbn [cube_xor fst snd]. rewrite !cube_nonzero_double.
  rewrite cube_xor_zero, cube_nonzero_zero. reflexivity.
Qed.

Lemma high_coordinate_in_span : forall order,
    sign_span (S (S (S order))) (fun input => snd input).
Proof.
  intros order.
  set (generator := schreier (S (S (S order)))
    (independent_first order, false) (independent_second order, false)).
  eapply span_extensional with
    (left := fun input => xorb (generator input) (generator (fst input, false))).
  - apply span_add.
    + apply span_generator.
    + apply (even_lower_in_span (S (S order)) (fun input => generator (input, false))).
      apply schreier_low_even.
  - intros [input high]. destruct high.
    + pose proof (schreier_high_difference (S (S order))
        (independent_first order) (independent_second order) input false false) as difference.
      rewrite independent_high_coefficient in difference.
      unfold generator. rewrite xorb_comm. exact difference.
    + apply xorb_nilpotent.
Qed.

Theorem schreier_span_lower : forall order function,
    even_lower_code (S (S order)) function -> sign_span (S (S (S order))) function.
Proof.
  intros order function [lower_function [high_coefficient [parity value]]].
  eapply span_extensional with (left := fun input =>
    xorb (lower_function (fst input)) (andb high_coefficient (snd input))).
  - apply span_add.
    + apply even_lower_in_span. exact parity.
    + destruct high_coefficient; simpl.
      * apply high_coordinate_in_span.
      * apply span_zero.
  - intros [lower high]. symmetry. apply value.
Qed.

Theorem schreier_span_characterization : forall order function,
    sign_span (S (S (S order))) function <-> even_lower_code (S (S order)) function.
Proof.
  intros order function. split; [apply schreier_span_upper | apply schreier_span_lower].
Qed.

Definition normalized_sign_span (order : nat) (function : cube order -> bool) : Prop :=
  exists raw, sign_span order raw /\
    forall input, function input = xorb (raw input) (raw (cube_zero order)).

Definition normalized_even_lower_code (order : nat) (function : cube (S order) -> bool) : Prop :=
  exists lower_function high_coefficient,
    cube_sum order lower_function = false /\ lower_function (cube_zero order) = false /\
    forall lower high, function (lower, high) =
      xorb (lower_function lower) (andb high_coefficient high).

Theorem normalized_schreier_characterization : forall order function,
    normalized_sign_span (S (S (S order))) function <->
    normalized_even_lower_code (S (S order)) function.
Proof.
  intros order function. split.
  - intros [raw [member normalized]].
    apply schreier_span_upper in member.
    destruct member as [lower_function [high_coefficient [parity value]]].
    exists (fun input => xorb (lower_function input) (lower_function (cube_zero (S (S order))))),
      high_coefficient. split.
    + rewrite cube_sum_xor, cube_sum_constant, parity. reflexivity.
    + split; [apply xorb_nilpotent |]. intros lower high.
      rewrite normalized.
      change (raw (cube_zero (S (S (S order))))) with
        (raw (cube_zero (S (S order)), false)).
      rewrite !value. cbv beta. btauto.
  - intros [lower_function [high_coefficient [parity [at_zero value]]]].
    exists function. split.
    + apply schreier_span_lower. exists lower_function, high_coefficient. auto.
    + intros input. change (function input = xorb (function input)
        (function (cube_zero (S (S order)), false))).
      rewrite value, at_zero, andb_false_r, xorb_false_r. reflexivity.
Qed.

Theorem scalar_sign_in_span : forall order,
    sign_span (S (S (S order))) (fun _ => true).
Proof.
  intros order. apply schreier_span_lower. exists (fun _ => true), false.
  split; [apply cube_sum_constant |]. intros lower high. reflexivity.
Qed.

(** Quaternion associativity leaves only the scalar sign direction. *)
Lemma quaternion_generator_constant : forall left right input : cube 2,
    schreier 2 left right input = schreier 2 left right (cube_zero 2).
Proof.
  intros [[[] left_low] left_high] [[[] right_low] right_high] [[[] input_low] input_high].
  destruct left_low, left_high, right_low, right_high, input_low, input_high; reflexivity.
Qed.

Theorem quaternion_span_constant : forall function,
    sign_span 2 function -> forall input, function input = function (cube_zero 2).
Proof.
  intros function member. induction member; intros input.
  - reflexivity.
  - apply quaternion_generator_constant.
  - rewrite IHmember1, IHmember2. reflexivity.
  - rewrite <- H, <- H. apply IHmember.
Qed.

Theorem quaternion_normalized_code_zero : forall function,
    normalized_sign_span 2 function <-> forall input, function input = false.
Proof.
  intros function. split.
  - intros [raw [member value]] input. rewrite value, (quaternion_span_constant raw member input).
    apply xorb_nilpotent.
  - intros value. exists (fun _ : cube 2 => false). split; [apply span_zero |].
    intros input. apply value.
Qed.

(** ANF coefficients are indexed by subsets represented as Boolean masks. *)
Fixpoint cube_ones (order : nat) : cube order :=
  match order with O => tt | S lower => (cube_ones lower, true) end.

Fixpoint anf_evaluate (order : nat) : (cube order -> bool) -> cube order -> bool :=
  match order with
  | O => fun coefficients _ => coefficients tt
  | S lower => fun coefficients input =>
      xorb (anf_evaluate lower (fun mask => coefficients (mask, false)) (fst input))
        (andb (snd input) (anf_evaluate lower (fun mask => coefficients (mask, true)) (fst input)))
  end.

Fixpoint monomial (order : nat) : cube order -> cube order -> bool :=
  match order with
  | O => fun _ _ => true
  | S lower => fun mask input =>
      andb (monomial lower (fst mask) (fst input)) (orb (negb (snd mask)) (snd input))
  end.

Lemma anf_evaluate_extensional : forall order left right,
    (forall mask, left mask = right mask) -> forall input,
    anf_evaluate order left input = anf_evaluate order right input.
Proof.
  induction order; intros left right equal input; [apply equal |].
  destruct input as [input high]. simpl.
  rewrite (IHorder (fun mask => left (mask, false)) (fun mask => right (mask, false))),
    (IHorder (fun mask => left (mask, true)) (fun mask => right (mask, true))); auto.
Qed.

Lemma anf_evaluate_xor : forall order left right input,
    anf_evaluate order (fun mask => xorb (left mask) (right mask)) input =
    xorb (anf_evaluate order left input) (anf_evaluate order right input).
Proof.
  induction order; intros left right input; [reflexivity |].
  destruct input as [input high]. simpl. rewrite !IHorder. btauto.
Qed.

Lemma anf_evaluate_false : forall order input,
    anf_evaluate order (fun _ => false) input = false.
Proof.
  induction order; intros input; [reflexivity |].
  destruct input as [input high]. simpl. rewrite IHorder. destruct high; reflexivity.
Qed.

Theorem anf_evaluate_involutive : forall order coefficients input,
    anf_evaluate order (anf_evaluate order coefficients) input = coefficients input.
Proof.
  induction order; intros coefficients input.
  - destruct input. reflexivity.
  - destruct input as [input high].
    change (xorb
      (anf_evaluate order (fun mask => xorb
        (anf_evaluate order (fun lower => coefficients (lower, false)) mask)
        (andb false (anf_evaluate order (fun lower => coefficients (lower, true)) mask))) input)
      (andb high (anf_evaluate order (fun mask => xorb
        (anf_evaluate order (fun lower => coefficients (lower, false)) mask)
        (andb true (anf_evaluate order (fun lower => coefficients (lower, true)) mask))) input))
      = coefficients (input, high)).
    cbn [andb]. rewrite !anf_evaluate_xor, anf_evaluate_false, !IHorder.
    destruct high; simpl; btauto.
Qed.

Theorem anf_evaluate_injective : forall order left right,
    (forall input, anf_evaluate order left input = anf_evaluate order right input) ->
    forall mask, left mask = right mask.
Proof.
  intros order left right equal mask.
  rewrite <- (anf_evaluate_involutive order left mask),
    <- (anf_evaluate_involutive order right mask).
  apply anf_evaluate_extensional. exact equal.
Qed.

Lemma anf_evaluate_zero : forall order coefficients,
    anf_evaluate order coefficients (cube_zero order) = coefficients (cube_zero order).
Proof.
  induction order; intros coefficients; [reflexivity |].
  cbn [cube_zero anf_evaluate fst snd]. rewrite xorb_false_r. apply IHorder.
Qed.

Lemma anf_evaluate_ones : forall order coefficients,
    anf_evaluate order coefficients (cube_ones order) = cube_sum order coefficients.
Proof.
  induction order; intros coefficients; [reflexivity |].
  cbn [cube_ones anf_evaluate cube_sum fst snd]. rewrite !IHorder. reflexivity.
Qed.

Lemma anf_evaluate_parity : forall order coefficients,
    cube_sum order (anf_evaluate order coefficients) = coefficients (cube_ones order).
Proof.
  intros order coefficients. rewrite <- anf_evaluate_ones. apply anf_evaluate_involutive.
Qed.

Lemma anf_evaluate_monomial_sum : forall order coefficients input,
    anf_evaluate order coefficients input =
    cube_sum order (fun mask => andb (coefficients mask) (monomial order mask input)).
Proof.
  induction order; intros coefficients input.
  - simpl. symmetry. apply andb_true_r.
  - destruct input as [input high]. cbn [anf_evaluate cube_sum monomial fst snd].
    rewrite !IHorder.
    assert (lower : cube_sum order (fun mask =>
      andb (coefficients (mask, false)) (andb (monomial order mask input) (orb (negb false) high))) =
      cube_sum order (fun mask => andb (coefficients (mask, false)) (monomial order mask input))).
    { apply cube_sum_extensional. intros mask. btauto. }
    rewrite lower. f_equal.
    rewrite <- cube_sum_and_constant. apply cube_sum_extensional. intros mask. btauto.
Qed.

Theorem monomial_basis_independent : forall order coefficients,
    (forall input, cube_sum order (fun mask =>
      andb (coefficients mask) (monomial order mask input)) = false) ->
    forall mask, coefficients mask = false.
Proof.
  intros order coefficients zero.
  apply (anf_evaluate_injective order coefficients (fun _ => false)).
  intros input. rewrite anf_evaluate_monomial_sum, zero, anf_evaluate_false. reflexivity.
Qed.

Lemma monomial_zero : forall order input,
    monomial order (cube_zero order) input = true.
Proof.
  induction order; intros input; [reflexivity |].
  destruct input as [input high]. simpl. rewrite IHorder. reflexivity.
Qed.

Lemma anf_monomial_basis : forall order mask input,
    anf_evaluate order (fun selected => cube_equal order selected mask) input =
    monomial order mask input.
Proof.
  intros order mask input. rewrite anf_evaluate_monomial_sum.
  transitivity (cube_sum order (fun selected =>
    andb (monomial order selected input) (cube_equal order selected mask))).
  - apply cube_sum_extensional. intros selected. apply andb_comm.
  - exact (cube_sum_sampling order (fun selected => monomial order selected input) mask).
Qed.

Lemma anf_scalar_delta : forall order scalar input,
    anf_evaluate order (fun mask => andb scalar (cube_equal order mask (cube_zero order))) input = scalar.
Proof.
  intros order [] input; simpl.
  - rewrite anf_monomial_basis. apply monomial_zero.
  - apply anf_evaluate_false.
Qed.

Definition normalized_basis_mask (order : nat) (mask : cube (S order)) : bool :=
  if snd mask then cube_equal order (fst mask) (cube_zero order)
  else andb (cube_nonzero order (fst mask)) (negb (cube_equal order (fst mask) (cube_ones order))).

Definition supported_anf (order : nat) (coefficients : cube (S order) -> bool) : Prop :=
  forall mask, normalized_basis_mask order mask = false -> coefficients mask = false.

Theorem normalized_anf_spanning : forall order function,
    normalized_sign_span (S (S (S order))) function <->
    exists coefficients, supported_anf (S (S order)) coefficients /\
      forall input, function input = anf_evaluate (S (S (S order))) coefficients input.
Proof.
  intros order function. rewrite normalized_schreier_characterization. split.
  - intros [lower_function [high_coefficient [parity [at_zero value]]]].
    exists (fun mask : cube (S (S (S order))) => if snd mask
      then andb high_coefficient (cube_equal (S (S order)) (fst mask) (cube_zero (S (S order))))
      else anf_evaluate (S (S order)) lower_function (fst mask)).
    split.
    + intros [mask high] excluded. destruct high.
      * cbn [normalized_basis_mask fst snd] in excluded |- *. rewrite excluded. apply andb_false_r.
      * cbn [normalized_basis_mask fst snd] in excluded |- *.
        apply andb_false_iff in excluded. destruct excluded as [at_origin | at_full].
        -- unfold cube_nonzero in at_origin. apply negb_false_iff in at_origin.
           apply cube_equal_spec in at_origin. subst mask. rewrite anf_evaluate_zero. exact at_zero.
        -- apply negb_false_iff in at_full. apply cube_equal_spec in at_full. subst mask.
           rewrite anf_evaluate_ones. exact parity.
    + intros [input high]. change (function (input, high) =
        xorb (anf_evaluate (S (S order)) (anf_evaluate (S (S order)) lower_function) input)
          (andb high (anf_evaluate (S (S order))
            (fun mask => andb high_coefficient
              (cube_equal (S (S order)) mask (cube_zero (S (S order))))) input))).
      rewrite anf_evaluate_involutive, anf_scalar_delta, value. rewrite andb_comm. reflexivity.
  - intros [coefficients [supported value]].
    exists (anf_evaluate (S (S order)) (fun mask => coefficients (mask, false))),
      (coefficients (cube_zero (S (S order)), true)).
    assert (high_support : forall mask,
      coefficients (mask, true) = andb (coefficients (cube_zero (S (S order)), true))
        (cube_equal (S (S order)) mask (cube_zero (S (S order))))).
    { intros mask. destruct (cube_equal (S (S order)) mask (cube_zero (S (S order)))) eqn:origin.
      - apply cube_equal_spec in origin. subst mask. symmetry. apply andb_true_r.
      - rewrite andb_false_r. apply supported. exact origin. }
    split.
    + rewrite anf_evaluate_parity. apply supported.
      unfold normalized_basis_mask. cbn [fst snd].
      rewrite cube_equal_reflexive. apply andb_false_r.
    + split.
      * rewrite anf_evaluate_zero. apply supported.
        unfold normalized_basis_mask. cbn [fst snd].
        rewrite cube_nonzero_zero. reflexivity.
      * intros input high. rewrite value.
        change (xorb (anf_evaluate (S (S order)) (fun mask => coefficients (mask, false)) input)
          (andb high (anf_evaluate (S (S order)) (fun mask => coefficients (mask, true)) input)) =
          xorb (anf_evaluate (S (S order)) (fun mask => coefficients (mask, false)) input)
            (andb (coefficients (cube_zero (S (S order)), true)) high)).
        rewrite (anf_evaluate_extensional (S (S order)) _ _ high_support), anf_scalar_delta.
        rewrite andb_comm. reflexivity.
Qed.

Theorem normalized_anf_coefficients_unique : forall order function first second,
    (forall input, function input = anf_evaluate (S (S (S order))) first input) ->
    (forall input, function input = anf_evaluate (S (S (S order))) second input) ->
    forall mask, first mask = second mask.
Proof.
  intros order function first second first_value second_value.
  apply anf_evaluate_injective. intros input. rewrite <- first_value, <- second_value. reflexivity.
Qed.

Theorem normalized_monomial_member : forall order mask,
    normalized_basis_mask (S (S order)) mask = true ->
    normalized_sign_span (S (S (S order))) (monomial (S (S (S order))) mask).
Proof.
  intros order mask admitted. apply normalized_anf_spanning.
  exists (fun selected => cube_equal (S (S (S order))) selected mask). split.
  - intros selected excluded.
    destruct (cube_equal (S (S (S order))) selected mask) eqn:equal; [| reflexivity].
    apply cube_equal_spec in equal. subst selected. rewrite admitted in excluded. discriminate.
  - intros input. symmetry. apply anf_monomial_basis.
Qed.

Fixpoint cube_count (order : nat) : (cube order -> bool) -> nat :=
  match order with
  | O => fun predicate => if predicate tt then 1 else 0
  | S lower => fun predicate =>
      cube_count lower (fun input => predicate (input, false)) +
      cube_count lower (fun input => predicate (input, true))
  end.

Lemma cube_count_extensional : forall order left right,
    (forall input, left input = right input) -> cube_count order left = cube_count order right.
Proof.
  induction order; intros left right equal.
  - simpl. rewrite equal. reflexivity.
  - simpl. rewrite (IHorder (fun input => left (input, false)) (fun input => right (input, false))),
      (IHorder (fun input => left (input, true)) (fun input => right (input, true))); auto.
Qed.

Lemma cube_count_false : forall order, cube_count order (fun _ => false) = 0.
Proof. induction order; simpl; [reflexivity | rewrite IHorder; reflexivity]. Qed.

Lemma cube_count_and_constant : forall order predicate constant,
    cube_count order (fun input => andb constant (predicate input)) =
    if constant then cube_count order predicate else 0.
Proof. intros order predicate []; simpl; [reflexivity | apply cube_count_false]. Qed.

Lemma cube_count_delta : forall order target,
    cube_count order (fun input => cube_equal order input target) = 1.
Proof.
  induction order; intros target; [reflexivity |].
  destruct target as [target high]. cbn [cube_count cube_equal fst snd].
  assert (slice : forall value,
    cube_count order (fun input => andb (cube_equal order input target) value) =
      if value then 1 else 0).
  { intros value. transitivity
      (cube_count order (fun input => andb value (cube_equal order input target))).
    - apply cube_count_extensional. intros input. apply andb_comm.
    - rewrite cube_count_and_constant, IHorder. reflexivity. }
  rewrite !slice. destruct high; reflexivity.
Qed.

Lemma cube_count_complement : forall order predicate,
    cube_count order predicate + cube_count order (fun input => negb (predicate input)) = 2 ^ order.
Proof.
  induction order; intros predicate.
  - simpl. destruct (predicate tt); reflexivity.
  - simpl. pose proof (IHorder (fun input => predicate (input, false))) as low.
    pose proof (IHorder (fun input => predicate (input, true))) as high. lia.
Qed.

Lemma cube_count_union : forall order left right,
    cube_count order (fun input => orb (left input) (right input)) +
    cube_count order (fun input => andb (left input) (right input)) =
    cube_count order left + cube_count order right.
Proof.
  induction order; intros left right.
  - simpl. destruct (left tt), (right tt); reflexivity.
  - simpl. pose proof (IHorder (fun input => left (input, false))
      (fun input => right (input, false))) as low.
    pose proof (IHorder (fun input => left (input, true))
      (fun input => right (input, true))) as high. lia.
Qed.

Lemma cube_zero_ones_distinct : forall order,
    cube_equal (S order) (cube_zero (S order)) (cube_ones (S order)) = false.
Proof.
  intros order. cbn [cube_equal cube_zero cube_ones fst snd]. apply andb_false_r.
Qed.

Lemma proper_nonempty_mask_count : forall order,
    cube_count (S order) (fun mask => andb (cube_nonzero (S order) mask)
      (negb (cube_equal (S order) mask (cube_ones (S order))))) + 2 = 2 ^ (S order).
Proof.
  intros order.
  pose proof (cube_count_union (S order)
    (fun mask => cube_equal (S order) mask (cube_zero (S order)))
    (fun mask => cube_equal (S order) mask (cube_ones (S order)))) as union.
  assert (overlap : cube_count (S order) (fun mask =>
    andb (cube_equal (S order) mask (cube_zero (S order)))
      (cube_equal (S order) mask (cube_ones (S order)))) = 0).
  { transitivity (cube_count (S order) (fun _ => false)); [| apply cube_count_false].
    apply cube_count_extensional. intros mask.
    destruct (cube_equal (S order) mask (cube_zero (S order))) eqn:at_zero; simpl; [| reflexivity].
    apply cube_equal_spec in at_zero. subst mask. apply cube_zero_ones_distinct. }
  cbv beta in union. rewrite overlap, !cube_count_delta in union.
  pose proof (cube_count_complement (S order) (fun mask => orb
    (cube_equal (S order) mask (cube_zero (S order)))
    (cube_equal (S order) mask (cube_ones (S order))))) as complement.
  assert (proper : cube_count (S order) (fun mask => andb (cube_nonzero (S order) mask)
      (negb (cube_equal (S order) mask (cube_ones (S order))))) =
    cube_count (S order) (fun mask => negb (orb
      (cube_equal (S order) mask (cube_zero (S order)))
      (cube_equal (S order) mask (cube_ones (S order)))))).
  { apply cube_count_extensional. intros mask. unfold cube_nonzero. btauto. }
  rewrite proper. lia.
Qed.

(** Independent, spanning ANF vectors are indexed by exactly this many masks.
    With total order n = order+3, the count is 2^(n-1)-1. *)
Theorem normalized_anf_basis_cardinality : forall order,
    cube_count (S (S (S order))) (normalized_basis_mask (S (S order))) =
    2 ^ (S (S order)) - 1.
Proof.
  intros order. change (cube_count (S (S order)) (fun mask =>
    andb (cube_nonzero (S (S order)) mask)
      (negb (cube_equal (S (S order)) mask (cube_ones (S (S order)))))) +
    cube_count (S (S order)) (fun mask => cube_equal (S (S order)) mask (cube_zero (S (S order)))) =
    2 ^ (S (S order)) - 1).
  rewrite cube_count_delta. pose proof (proper_nonempty_mask_count (S order)). lia.
Qed.

Theorem normalized_span_intersection : forall order function,
    normalized_sign_span (S (S (S order))) function <->
    sign_span (S (S (S order))) function /\ function (cube_zero (S (S (S order)))) = false.
Proof.
  intros order function. split.
  - intros [raw [member value]]. split.
    + eapply span_extensional with (left := fun input => xorb (raw input) (raw (cube_zero (S (S (S order)))))).
      * apply span_add; [exact member |].
        destruct (raw (cube_zero (S (S (S order))))); [apply scalar_sign_in_span | apply span_zero].
      * intros input. symmetry. apply value.
    + rewrite value. apply xorb_nilpotent.
  - intros [member at_zero]. exists function. split; [exact member |].
    intros input. rewrite at_zero, xorb_false_r. reflexivity.
Qed.

Theorem schreier_scalar_direct_sum : forall order raw,
    sign_span (S (S (S order))) raw ->
    normalized_sign_span (S (S (S order)))
      (fun input => xorb (raw input) (raw (cube_zero (S (S (S order)))))) /\
    (forall input, raw input =
      xorb (xorb (raw input) (raw (cube_zero (S (S (S order))))))
        (raw (cube_zero (S (S (S order)))))) /\
    (forall normalized scalar,
      normalized_sign_span (S (S (S order))) normalized ->
      (forall input, raw input = xorb (normalized input) scalar) ->
      scalar = raw (cube_zero (S (S (S order)))) /\
      forall input, normalized input = xorb (raw input) (raw (cube_zero (S (S (S order)))))).
Proof.
  intros order raw member. split.
  - exists raw. split; [exact member | reflexivity].
  - split.
    + intros input. btauto.
    + intros normalized scalar normalized_member value.
      apply normalized_span_intersection in normalized_member.
      destruct normalized_member as [_ at_zero].
      assert (scalar_value : scalar = raw (cube_zero (S (S (S order))))).
      { rewrite value, at_zero. reflexivity. }
      split; [exact scalar_value |]. intros input. rewrite value, <- scalar_value. btauto.
Qed.

